"""Render the generated rural-Florida scenario report (Markdown).

The report is deterministic: same scenario file, same bytes. Do not edit
docs/scenario-report.md by hand; tests/test_report.py fails when the
committed report and the model disagree.
"""

import json

from .model import (
    canopy_area_m2,
    crop_rows,
    energy_balance,
    water_balance,
    zone_footprint_m2,
)


def _table(headers, rows):
    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join(["---"] * len(headers)) + "|")
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def _bullets(items):
    return "\n".join(f"- {item}" for item in items)


def render_report(cfg, title=None):
    name = cfg["scenario"]["name"]
    wb = water_balance(cfg)
    eb = energy_balance(cfg)
    crops = crop_rows(cfg)
    indoor_kg = sum(r["annual_kg"] for r in crops if not r["screenhouse"])
    screen_kg = sum(r["annual_kg"] for r in crops if r["screenhouse"])

    a = []
    a.append(f"# {title or (name + ' - generated scenario report')}")
    a.append("")
    a.append("Generated by `PYTHONPATH=src python -m floridafarm report --out docs/scenario-report.md`.")
    a.append("Do not edit by hand: `tests/test_report.py` fails when this file and the model disagree.")
    a.append("")
    a.append("Every number below is arithmetic on the labeled placeholder assumptions in")
    a.append("`config/scenario.json`. Status: " + cfg["scenario"]["status"] + ".")
    a.append("Nothing here is a measurement, price quote or performance claim.")
    a.append("")

    a.append("## 1. Scenario summary")
    a.append("")
    a.append(_table(["Field", "Value"], [
        ["Scenario", name],
        ["Version", cfg["scenario"].get("version", "unversioned")],
        ["Location placeholder", cfg["scenario"]["location_placeholder"]],
        ["Indoor canopy area (m2)", f"{canopy_area_m2(cfg):.0f}"],
        ["Indoor zone footprint (m2)", f"{zone_footprint_m2(cfg):.0f}"],
        ["Screenhouse area (m2)", f"{cfg['campus']['screenhouse_area_m2']:.0f}"],
        ["Raised floor height (m)", f"{cfg['campus']['raised_floor_height_m']:.2f}"],
        ["Design hurricane category (placeholder)", cfg["climate"]["design_hurricane_category_placeholder"]],
        ["Freeze events per year (placeholder)", cfg["climate"]["freeze_events_per_year"]],
        ["Humid season months (placeholder)", cfg["climate"]["humid_season_months"]],
    ]))
    a.append("")

    a.append("## 2. Crop matrix (placeholder yields)")
    a.append("")
    a.append(_table(
        ["Crop", "System", "Area m2", "Cycles/yr", "kg/cycle", "kg/yr"],
        [[r["name"], r["system"], f"{r['area_m2']:.0f}", f"{r['cycles_per_year']:.1f}",
          f"{r['kg_per_cycle']:.0f}", f"{r['annual_kg']:.0f}"] for r in crops],
    ))
    a.append("")
    a.append(f"Indoor total: {indoor_kg:.0f} kg/yr. Screenhouse (citrus) total: {screen_kg:.0f} kg/yr.")
    a.append("Placeholder yields only: a first crop-cycle audit must measure real water/kg")
    a.append("and energy/kg before any number here is treated as dependable.")
    a.append("")

    a.append("## 3. Water balance (per day)")
    a.append("")
    a.append(_table(["Item", "Value"], [
        ["Indoor uptake (L/day)", f"{wb['uptake_indoor_l_per_day']:.0f}"],
        ["Screenhouse uptake (L/day)", f"{wb['uptake_screenhouse_l_per_day']:.0f}"],
        ["Total uptake (L/day)", f"{wb['uptake_l_per_day']:.0f}"],
        ["Recirculated (L/day)", f"{wb['recirculated_l_per_day']:.0f}"],
        ["Purge before recovery (L/day)", f"{wb['purge_l_per_day']:.0f}"],
        ["Condensate recovery (L/day)", f"{wb['condensate_l_per_day']:.0f}"],
        ["Net makeup water (L/day)", f"{wb['net_makeup_l_per_day']:.1f}"],
        ["Rain harvest (L/day)", f"{wb['rain_harvest_l_per_day']:.0f}"],
        ["Irrigation tank at placeholder backup days (L)", f"{wb['irrigation_tank_l']:.0f}"],
        ["Tank coverage of full uptake (days)", f"{wb['tank_days_of_full_uptake']:.2f}"],
        ["Disinfection stage", cfg["water"]["disinfection_stage"]],
        ["Purge handling", cfg["water"]["purge_handling"]],
    ]))
    a.append("")
    a.append("Honest reading: at these placeholders, rain harvest exceeds net makeup several")
    a.append("times over, and the makeup-sized tank looks tiny next to full uptake. Storage is")
    a.append("NOT designed here; storm mode and dry spells set the real target on a real site.")
    a.append("")
    a.append("## 4. Energy balance (per day)")
    a.append("")
    a.append(_table(["Item", "Value"], [
        ["LED load (kWh/day)", f"{eb['led_kwh_per_day']:.0f}"],
        ["HVAC / dehumidification (kWh/day)", f"{eb['hvac_kwh_per_day']:.0f}"],
        ["Pumps (kWh/day)", f"{eb['pumps_kwh_per_day']:.0f}"],
        ["Packhouse refrigeration (kWh/day)", f"{eb['refrigeration_kwh_per_day']:.0f}"],
        ["Controls (kWh/day)", f"{eb['controls_kwh_per_day']:.0f}"],
        ["Total (kWh/day)", f"{eb['total_kwh_per_day']:.0f}"],
        ["Solar production (kWh/day)", f"{eb['solar_kwh_per_day']:.0f}"],
        ["Solar fraction of modeled load", f"{eb['solar_fraction'] * 100:.1f}%"],
        ["kWp needed for a 50% solar fraction", f"{eb['kwp_for_50pct_fraction']:.0f} kWp"],
        ["Critical loads (kWh/day)", f"{eb['critical_load_kwh_per_day']:.0f}"],
        ["Average critical load (kW)", f"{eb['critical_load_kw_avg']:.1f}"],
        ["Battery autonomy on critical loads (h)", f"{eb['battery_autonomy_hours']:.1f}"],
        ["Battery vs 12 h design target", eb["battery_vs_target"]],
    ]))
    a.append("")
    a.append(f"Honest reading: the placeholder {cfg['campus']['battery_kwh']:.0f} kWh battery does")
    a.append(
        f"{eb['battery_vs_target']} against the {cfg['campus']['design_backup_autonomy_hours']:.0f} h"
        f" design target: {eb['battery_autonomy_hours']:.1f} h on critical loads. A real design"
    )
    a.append("resizes the battery, adds a generator, or accepts the gap explicitly. Solar is")
    a.append("never assumed to power the whole farm.")
    a.append("")

    a.append("## 5. Resilience and automation checklist")
    a.append("")
    a.append("Local-first control: " + ("yes" if cfg["automation"]["local_first_control"] else "no"))
    a.append("")
    a.append("N+1 redundancy (verified by the qualification ladder, never assumed):")
    a.append(_bullets(cfg["automation"]["n_plus_1"]))
    a.append("")
    a.append("Storm mode checklist (a qualification item, not an assumption):")
    a.append(_bullets(cfg["automation"]["storm_mode_checklist"]))
    a.append("")
    a.append("Qualification ladder:")
    a.append(_bullets(cfg["automation"]["qualification_ladder"]))
    a.append("")

    a.append("## 6. Assumptions (config/scenario.json)")
    a.append("")
    a.append("```json")
    a.append(json.dumps(cfg, indent=2, ensure_ascii=False))
    a.append("```")
    a.append("")
    a.append("---")
    a.append("Rural Florida scenario, labeled placeholder arithmetic. Not engineering,")
    a.append("survey or construction data. Regenerate after editing the scenario file.")
    a.append("")
    return "\n".join(a)